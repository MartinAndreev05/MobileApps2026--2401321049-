// ---- Test coverage (JaCoCo) ----
// ./gradlew jacocoTestReport  ->  app/build/reports/jacoco/jacocoTestReport/html/index.html
// Code generated by tools (view binding, Hilt, Room, Safe Args, R) is left out:
// it is not written by hand and would only dilute the percentage.
val coverageExcludes = listOf(
    "**/R.class",
    "**/R$*.class",
    "**/BuildConfig.*",
    "**/Manifest*.*",
    "**/databinding/**",
    "**/hilt_aggregated_deps/**",
    "**/dagger/**",
    "**/Hilt_*.*",
    "**/*_HiltModules*.*",
    "**/*_HiltComponents*.*",
    "**/*_Factory.*",
    "**/*_Factory$*.*",
    "**/*_Provide*Factory*.*",
    "**/*_MembersInjector.*",
    "**/*_GeneratedInjector.*",
    "**/*_ComponentTreeDeps*.*",
    "**/*_Impl*.*",
    "**/*Directions*.*",
    "**/*FragmentArgs*.*",
)

val unitTestCoverageData =
    layout.buildDirectory.file("outputs/unit_test_code_coverage/debugUnitTest/testDebugUnitTest.exec")

// The classes exactly as the unit tests ran them (after Hilt's bytecode transform).
val coverageClasses = fileTree(layout.buildDirectory.dir("intermediates/classes/debug/transformDebugClassesWithAsm/dirs")) {
    exclude(coverageExcludes)
}

tasks.register<JacocoReport>("jacocoTestReport") {
    group = "verification"
    description = "Runs the unit tests and creates an HTML/XML coverage report without generated code."
    dependsOn("testDebugUnitTest")
    classDirectories.setFrom(coverageClasses)
    sourceDirectories.setFrom(files("src/main/java"))
    executionData.setFrom(unitTestCoverageData)
    reports {
        html.required = true
        xml.required = true
    }
}

tasks.register<JacocoCoverageVerification>("jacocoTestCoverageVerification") {
    group = "verification"
    description = "Fails the build if unit test line coverage drops below the course minimum."
    dependsOn("testDebugUnitTest")
    classDirectories.setFrom(coverageClasses)
    sourceDirectories.setFrom(files("src/main/java"))
    executionData.setFrom(unitTestCoverageData)
    violationRules {
        rule {
            limit {
                counter = "LINE"
                minimum = "0.15".toBigDecimal()
            }
        }
    }
}

